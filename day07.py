import numpy as np 
import pandas as pd

# Создание массива и вывод некоторых операций над ним
np_list = np.array([3, 8, 1, 14, 7, 20, 5])

print(np_list) # вывод самого массива
print(np_list * 2) # вывод удвоенных элементов
print(np_list[np_list > 5]) # вывод элементов больше 5
print(np_list.mean()) # вывод среднего значения
print(np_list.argmax()) # вывод индекса максимального значения


# Скалярное произведение векторов A и B

A = [1, 2, 3] # вектор A
B = [4, 5, 6] # вектор B

result = 0

# способ придумал сам на ходу
for i in range(len(A)):
    product = A[0 + i] * B[0 + i]
    result += product

print(result)

# способ через NumPy

A = np.array([1, 2, 3]) # вектор A преобразован в массив
B = np.array([4, 5, 6]) # вектор B преобразован в массив

print(np.dot(A, B))


# Матрицы.

# матрица A (2 x 3)
A = np.array([[1, 2, 3],
                [4, 5, 6]])

# матрица B (3 x 2)
B = np.array([[7, 8],
            [9, 10], 
            [11, 12]])

print(f"{A.shape}, {B.shape}") # вывод размеров
print(A @ B) # ответ: матрица (2 x 2).


# Первое "предсказание" стоимости 3 домов.

X = np.array([[50, 1], [80, 2], [100, 3]]) # признаки: (площадь, число комнат).
W = np.array([1000, 5000]) # веса модели.

result = (X @ W) + 10000 # скалярное произведение признаков на веса + 10.000 (постоянная добавка).

print(result)


